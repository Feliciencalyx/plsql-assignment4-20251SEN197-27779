
CREATE TABLE A4_STUDENT.GRADES (
    grade_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enrollment_id NUMBER NOT NULL,
    marks NUMBER(5,2) NOT NULL,
    letter_grade VARCHAR2(2),
    remarks VARCHAR2(100),
    grading_date DATE DEFAULT SYSDATE,

    CONSTRAINT fk_grade_enrollment
        FOREIGN KEY (enrollment_id)
        REFERENCES A4_STUDENT.ENROLLMENTS(enrollment_id),

    CONSTRAINT chk_marks
        CHECK (marks BETWEEN 0 AND 100)
);
CREATE TABLE A4_STUDENT.ENROLLMENTS (
    enrollment_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id NUMBER NOT NULL,
    course_id NUMBER NOT NULL,
    academic_year VARCHAR2(20) NOT NULL,
    semester VARCHAR2(20) NOT NULL,
    enrollment_date DATE DEFAULT SYSDATE,
    status VARCHAR2(20) DEFAULT 'ENROLLED',
    CONSTRAINT fk_enroll_student
        FOREIGN KEY (student_id)
        REFERENCES A4_STUDENT.STUDENTS(student_id),
    CONSTRAINT fk_enroll_course
        FOREIGN KEY (course_id)
        REFERENCES A4_STUDENT.COURSES(course_id),
    CONSTRAINT uq_student_course_term
        UNIQUE (student_id, course_id, academic_year, semester)
);
CREATE TABLE A4_STUDENT.COURSES (
    course_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_code VARCHAR2(20) UNIQUE NOT NULL,
    course_name VARCHAR2(100) NOT NULL,
    credit_hours NUMBER(2) NOT NULL,
    department VARCHAR2(100),
    status VARCHAR2(20) DEFAULT 'ACTIVE',
    CONSTRAINT chk_credit_hours CHECK (credit_hours > 0)
);
CREATE TABLE A4_STUDENT.STUDENTS (
    student_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR2(50) NOT NULL,
    last_name VARCHAR2(50) NOT NULL,
    email VARCHAR2(100) UNIQUE NOT NULL,
    date_of_birth DATE,
    registration_date DATE DEFAULT SYSDATE,
    status VARCHAR2(20) DEFAULT 'ACTIVE'
);